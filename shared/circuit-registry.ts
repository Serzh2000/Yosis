const table = (rows: string[]) => rows;
const gateSketch = (f: (a: number, b: number) => number) =>
  table(['A B │ Y', ...[0, 1].flatMap((a) => [0, 1].map((b) => `${a} ${b} │ ${f(a, b)}`))]);
