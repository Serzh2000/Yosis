def rw(path, text=None):
    if text is None:
        return io.open(path, encoding='utf8').read()
    io.open(path, 'w', encoding='utf8', newline='\n').write(text)


for ch, (key, items) in T.items():
    path = os.path.join(CH, ch + '.tex')
    s = rw(path)
    if r'\section{Вопросы и задачи}' in s:
        continue
    body = '\n'.join('  \\item ' + t for t in items)
    block = (
        '\\section{Вопросы и задачи}\n\\label{sec:tasks-%s}\n\n'
        'Ответы собраны в приложении~\\ref{app:answers}.\n\n'
        '\\begin{taskbox}[Задачи к главе]\n\\begin{enumerate}\n%s\n\\end{enumerate}\n\\end{taskbox}\n'
    ) % (key, body)
    if ch == 'b9_sync':
        s = s.replace('\\section{Что дальше}', block + '\n\\section{Что дальше}', 1)
    else:
        s = s.rstrip('\n') + '\n\n' + block
    rw(path, s)

out = ['\\chapter{Ответы к задачам первой части}\n\\label{app:answers}\n\n']
for ch, (key, items) in T.items():
    out.append('\\section*{%s}\n\\begin{enumerate}\n' % NAMES[key])
    out.append('\n'.join('  \\item ' + a for a in ANS[key]))
    out.append('\n\\end{enumerate}\n\n')
rw(os.path.join(CH, 'a2_answers.tex'), ''.join(out))
