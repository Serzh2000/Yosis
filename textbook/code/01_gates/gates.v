// Пример 1. Логические элементы на кнопках.
// Две кнопки -- два входа, шесть светодиодов -- шесть функций.
// Светодиоды на плате загораются от нуля, поэтому на выходе стоит инверсия.
module gates (
    input  wire [1:0] btn,   // btn[0] = S1 (a), btn[1] = S2 (b)
    output wire [5:0] led    // активный уровень -- низкий
);
    wire a = btn[0];
    wire b = btn[1];

    wire [5:0] f;            // "логические" результаты: 1 = должен гореть

    assign f[0] = a & b;     // И
    assign f[1] = a | b;     // ИЛИ
    assign f[2] = ~a;        // НЕ
    assign f[3] = ~(a & b);  // И-НЕ
    assign f[4] = ~(a | b);  // ИЛИ-НЕ
    assign f[5] = a ^ b;     // Исключающее ИЛИ

    assign led = ~f;         // 1 -> 0 на ножке -> светодиод горит
endmodule
