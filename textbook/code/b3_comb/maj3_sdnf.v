// «2 из 3» в лоб, по СДНФ: по одному произведению на каждую строку таблицы, где y = 1.
module maj3_sdnf (
    input  a, b, c,
    output y
);
    assign y = (~a & b & c)    // строка 3: 011
             | (a & ~b & c)    // строка 5: 101
             | (a & b & ~c)    // строка 6: 110
             | (a & b & c);    // строка 7: 111
endmodule
