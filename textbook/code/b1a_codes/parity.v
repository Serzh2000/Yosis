// Пример 4. Бит чётности: передатчик дополняет цифру до чётного числа единиц, приёмник ловит ошибку.
module parity_tx (
    input  [3:0] d,         // данные (цифра BCD)
    output [4:0] word       // слово: бит чётности в старшем разряде
);
    wire p = ^d;            // ^d --- исключающее ИЛИ всех битов: 1, если единиц нечётное число
    assign word = {p, d};   // теперь в слове чётное число единиц
endmodule

module parity_rx (
    input  [4:0] word,      // принятое слово
    output       err        // 1 = число единиц нечётно, слово повреждено
);
    assign err = ^word;     // для целого слова результат должен быть 0
endmodule
