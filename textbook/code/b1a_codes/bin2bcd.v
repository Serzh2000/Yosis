// Пример 3. Перевод двоичного числа 0..255 в три цифры BCD (алгоритм «сдвиг и прибавь 3»).
module bin2bcd (
    input  [7:0] bin,       // двоичное число
    output reg [3:0] h,     // сотни
    output reg [3:0] t,     // десятки
    output reg [3:0] o      // единицы
);
    integer i;
    reg [19:0] sh;          // {сотни, десятки, единицы, исходное число}
    always @(*) begin
        sh = 20'd0;
        sh[7:0] = bin;
        for (i = 0; i < 8; i = i + 1) begin
            // перед сдвигом любую цифру 5..9 увеличиваем на 3: после сдвига получится поправка 6
            if (sh[11:8]  >= 4'd5) sh[11:8]  = sh[11:8]  + 4'd3;
            if (sh[15:12] >= 4'd5) sh[15:12] = sh[15:12] + 4'd3;
            if (sh[19:16] >= 4'd5) sh[19:16] = sh[19:16] + 4'd3;
            sh = sh << 1;
        end
        h = sh[19:16];
        t = sh[15:12];
        o = sh[11:8];
    end
endmodule
