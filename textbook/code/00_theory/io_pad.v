// Двунаправленная ножка: три состояния выхода (глава «Электрические основы и шины»).
// oe = 1 --- схема управляет ножкой; oe = 0 --- выход «отпущен» (высокоомное состояние Z),
// и ножку может ровно так же вести внешняя микросхема.
module io_pad (
    input        oe,        // разрешение выхода
    input  [3:0] to_pad,    // что выдаём наружу
    inout  [3:0] pad,       // сама ножка
    output [3:0] from_pad   // что видим на ножке
);
    assign pad      = oe ? to_pad : 4'bzzzz;
    assign from_pad = pad;
endmodule
