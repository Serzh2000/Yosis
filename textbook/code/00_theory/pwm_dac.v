// ЦАП на основе ШИМ (глава «Цифра и аналоговый мир»).
// Счётчик бежит по кругу 0..255, выход равен 1, пока счётчик меньше значения level.
// Среднее напряжение на выходе равно level/256 от питания; RC-фильтр делает из него
// постоянное напряжение.
module pwm_dac (
    input        clk,
    input  [7:0] level,    // желаемое «напряжение» 0..255
    output       pwm
);
    reg [7:0] cnt = 8'd0;
    always @(posedge clk) cnt <= cnt + 8'd1;
    assign pwm = (cnt < level);
endmodule
