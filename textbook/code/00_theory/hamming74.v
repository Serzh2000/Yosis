// Код Хэмминга (7,4): исправляет одну ошибку в семи принятых битах (глава «Системы счисления и коды»).
// Позиции 1..7:  p1 p2 d1 p3 d2 d3 d4.  Контрольные биты стоят на позициях-степенях двойки.
module hamming74 (
    input  [3:0] d,      // четыре бита данных
    input  [6:0] err,    // маска ошибки: единица переворачивает бит в канале
    output [6:0] sent,   // кодовое слово, как оно ушло в канал
    output [6:0] got,    // то, что пришло (с ошибкой)
    output [2:0] syn,    // синдром = номер повреждённой позиции (0 --- ошибки нет)
    output [3:0] q       // исправленные данные
);
    // Кодер: каждый контрольный бит --- чётность своей группы позиций
    wire p1 = d[0] ^ d[1] ^ d[3];    // позиции 1,3,5,7
    wire p2 = d[0] ^ d[2] ^ d[3];    // позиции 2,3,6,7
    wire p3 = d[1] ^ d[2] ^ d[3];    // позиции 4,5,6,7
    assign sent = {d[3], d[2], d[1], p3, d[0], p2, p1};

    // Канал: переворачиваем выбранные биты
    assign got = sent ^ err;

    // Декодер: пересчитываем чётности, нули означают «всё в порядке»
    wire s1 = got[0] ^ got[2] ^ got[4] ^ got[6];
    wire s2 = got[1] ^ got[2] ^ got[5] ^ got[6];
    wire s3 = got[3] ^ got[4] ^ got[5] ^ got[6];
    assign syn = {s3, s2, s1};

    // Исправление: переворачиваем бит на позиции syn
    wire [6:0] fixed = (syn == 3'd0) ? got : (got ^ (7'd1 << (syn - 3'd1)));
    assign q = {fixed[6], fixed[5], fixed[4], fixed[2]};
endmodule
