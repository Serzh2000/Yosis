// Пример 6. Переполнение со знаком и сумматор с насыщением.
module add4_ovf (
    input  [3:0] a, b,
    output [3:0] s,
    output       c3,         // перенос В старший разряд
    output       c4,         // перенос ИЗ старшего разряда
    output       v           // знаковое переполнение
);
    wire [3:0] low = {1'b0, a[2:0]} + {1'b0, b[2:0]};   // сумма трёх младших разрядов с запасным битом
    assign c3 = low[3];                                  // запасной бит --- перенос в старший разряд
    assign {c4, s[3]} = a[3] + b[3] + c3;
    assign s[2:0] = low[2:0];
    assign v = c3 ^ c4;                      // два слагаемых одного знака, результат другого
endmodule

module add4_sat (
    input  [3:0] a, b,       // знаковые числа в дополнительном коде
    output [3:0] s           // при переполнении: +7 (0111) или -8 (1000) вместо неверного результата
);
    wire [3:0] raw = a + b;
    wire       v   = (a[3] == b[3]) && (raw[3] != a[3]);    // знаки слагаемых равны, знак результата другой
    assign s = v ? (a[3] ? 4'b1000 : 4'b0111) : raw;        // отрицательные упираются в -8, положительные в +7
endmodule
