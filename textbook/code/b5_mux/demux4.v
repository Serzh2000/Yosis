// Пример 3. Демультиплексор 1:4: входной сигнал попадает на один выход, на остальных ноль.
module demux4 (
    input        x,           // информационный вход
    input  [1:0] s,           // адрес выхода
    output reg [3:0] y        // y[i] = x, если s = i, иначе 0
);
    always @(*) begin
        y = 4'b0000;          // значение по умолчанию: так y присваивается в любой ветке и защёлки нет
        case (s)
            2'd0: y[0] = x;
            2'd1: y[1] = x;
            2'd2: y[2] = x;
            2'd3: y[3] = x;
        endcase
    end
endmodule

// То же самое одной строкой: дешифратор со входом разрешения.
module demux4_shift (
    input        x,
    input  [1:0] s,
    output [3:0] y
);
    assign y = {3'b000, x} << s;   // единица (или ноль) x сдвигается на s позиций
endmodule
