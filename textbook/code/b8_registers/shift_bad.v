// ОШИБКА НОВИЧКА: блокирующие присваивания (=) в тактируемом блоке.
// Каждая строка видит уже новое значение предыдущей, и бит «пролетает» через
// все три триггера за один такт: получился не сдвиговый регистр, а один триггер.
module shift_bad (
    input      clk,
    input      d,
    output reg q0, q1, q2
);
    always @(posedge clk) begin
        q0 = d;      // q0 меняется сразу
        q1 = q0;     // читает уже НОВОЕ q0
        q2 = q1;     // читает уже НОВОЕ q1
    end
endmodule
