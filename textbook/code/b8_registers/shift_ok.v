// Правильный вариант: неблокирующие присваивания (<=) в тактируемом блоке.
// Все правые части вычисляются по СТАРЫМ значениям, потом все триггеры обновляются разом.
module shift_ok (
    input      clk,
    input      d,
    output reg q0, q1, q2
);
    always @(posedge clk) begin
        q0 <= d;
        q1 <= q0;    // старое q0
        q2 <= q1;    // старое q1
    end
endmodule
