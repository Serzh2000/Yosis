// Делитель частоты: из такта 27 МГц получаем меандр 1 Гц.
// Счётчик по модулю N выдаёт импульс tick раз в N тактов; он переключает T-триггер,
// поэтому полный период выхода равен 2*N тактов.
// 27 МГц: N = 13 500 000 даёт полпериода 0,5 с, то есть 1 Гц. Для тестбенча N уменьшают.
module clk_div #(parameter N = 13_500_000) (
    input  clk,
    output reg out = 1'b0,     // меандр: период 2*N тактов
    output tick                // импульс: раз в N тактов
);
    reg [24:0] cnt = 25'd0;    // 25 разрядов хватает до 2^25 = 33 554 432
    assign tick = (cnt == N - 1);
    always @(posedge clk) begin
        if (tick) begin
            cnt <= 25'd0;
            out <= ~out;       // T-триггер по импульсу
        end else
            cnt <= cnt + 25'd1;
    end
endmodule
