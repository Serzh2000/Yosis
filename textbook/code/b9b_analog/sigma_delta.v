// Сигма-дельта модулятор первого порядка: накопитель остатка, единица на выходе при переполнении.
// За 2**W тактов выход равен единице ровно level раз, причём единицы разбросаны по периоду равномерно.
module sigma_delta #(
    parameter W = 6              // разрядность уровня, период 2**W тактов
) (
    input          clk,
    input  [W-1:0] level,
    output         bit_out
);
    reg [W:0] acc = {(W+1){1'b0}};          // старший бит acc --- перенос прошлого сложения
    always @(posedge clk)
        acc <= {1'b0, acc[W-1:0]} + {1'b0, level};   // прибавляем уровень, остаток остаётся
    assign bit_out = acc[W];
endmodule
