// Шифратор 4->2 через case: унитарный код (одна единица) -> номер линии.
module enc4to2 (
    input      [3:0] x,   // x[i] = 1, если активна линия i
    output reg [1:0] y    // номер активной линии
);
    always @* begin
        case (x)
            4'b0001: y = 2'd0;
            4'b0010: y = 2'd1;
            4'b0100: y = 2'd2;
            4'b1000: y = 2'd3;
            default: y = 2'd0;   // не унитарный код: простой шифратор ничего разумного не скажет
        endcase
    end
endmodule
