// Тот же y = a*b + c без конвейера: одна длинная цепочка логики между регистрами.
// Задержка 1 такт, но допустимая тактовая частота ниже (умножитель + сумматор в одном такте).
module nopipe (
    input            clk,
    input      [3:0] a, b, c,
    output reg [8:0] y
);
    always @(posedge clk) y <= a * b + c;
endmodule
