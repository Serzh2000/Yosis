// Двухэтапный конвейер: y = a*b + c. Результат появляется через 2 такта после входов,
// но новые a, b, c принимаются КАЖДЫЙ такт. Каждый этап короче, поэтому такт можно сделать быстрее.
module pipe2 (
    input            clk,
    input      [3:0] a, b, c,
    output reg [8:0] y
);
    reg [7:0] prod;          // регистр между этапами 1 и 2
    reg [3:0] c1;            // c тоже надо задержать на один такт, чтобы он «ехал» вместе с a, b
    always @(posedge clk) begin
        prod <= a * b;       // этап 1: умножение
        c1   <= c;
        y    <= prod + c1;   // этап 2: сложение
    end
endmodule
