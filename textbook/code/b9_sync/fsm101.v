// Автомат Мура: детектор последовательности 101 с перекрытием (граф на рис. «Граф переходов»).
// Три части: (1) регистр состояния, (2) логика переходов, (3) логика выходов.
module fsm101 (
    input  clk,
    input  rst,       // синхронный сброс в S0
    input  x,         // входной бит, по одному за такт
    output y          // 1, когда принято 101
);
    localparam S0 = 2'd0,    // ничего не найдено
               S1 = 2'd1,    // принято «1»
               S2 = 2'd2,    // принято «10»
               S3 = 2'd3;    // принято «101»
    reg [1:0] state, next;

    // (1) регистр состояния
    always @(posedge clk) begin
        if (rst) state <= S0;
        else     state <= next;
    end

    // (2) логика переходов: по таблице переходов, для КАЖДОГО состояния и КАЖДОГО x
    always @* begin
        case (state)
            S0:      next = x ? S1 : S0;
            S1:      next = x ? S1 : S2;
            S2:      next = x ? S3 : S0;
            S3:      next = x ? S1 : S2;   // перекрытие: последняя 1 может начать новую тройку
            default: next = S0;            // защита от неописанных кодов
        endcase
    end

    // (3) логика выходов (Мур: зависит только от состояния)
    assign y = (state == S3);
endmodule
