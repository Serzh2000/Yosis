// Пример 3. Число на шине: шесть разрядов выводятся на шесть светодиодов, горящих от нуля.
module number_bus (
    input  [5:0] value,   // число 0..63, разряд 0 --- младший
    output [5:0] led_n    // светодиоды платы: горят при 0
);
    assign led_n = ~value;   // единица в разряде = ноль на выводе = светодиод горит
endmodule
