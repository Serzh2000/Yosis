// Пример 4. Делитель частоты на 2: выход меняется по каждому переднему фронту такта.
module clk_div2 (
    input  clk,       // такт
    output q          // частота в два раза ниже тактовой
);
    reg t = 1'b0;                 // память на один бит, начальное значение 0
    always @(posedge clk)         // по переднему фронту такта (переход 0 -> 1)
        t <= ~t;                  // перевернуть значение (неблокирующее присваивание)
    assign q = t;
endmodule
