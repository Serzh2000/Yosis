// Пример 2. Активный уровень: светодиод платы горит от нуля, кнопка сброса срабатывает от нуля.
module active_level (
    input  door,          // датчик двери: 1 = дверь открыта (активный высокий)
    input  rst_n,         // кнопка сброса: 0 = нажата (активный низкий, суффикс _n)
    output led_n,         // светодиод платы: горит при 0
    output reset_active   // внутренний сигнал «идёт сброс» в привычной полярности: 1 = сброс
);
    assign led_n        = ~door;    // дверь открыта (1) -> на выводе 0 -> светодиод горит
    assign reset_active = ~rst_n;   // кнопку нажали (0) -> reset_active = 1
endmodule
