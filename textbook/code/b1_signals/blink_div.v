// Пример 5. Счётчик-делитель: старший разряд счётчика мигает в 2^N раз медленнее такта.
module blink_div #(
    parameter N = 24      // разрядность счётчика: при 27 МГц N = 24 даёт около 1,6 Гц
) (
    input  clk,
    output led            // старший разряд счётчика
);
    reg [N-1:0] cnt = 0;                  // N-разрядный счётчик
    always @(posedge clk)
        cnt <= cnt + 1'b1;                // каждый такт +1; после переполнения снова 0
    assign led = cnt[N-1];                // период led равен 2^N тактам
endmodule
