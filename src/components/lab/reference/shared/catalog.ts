export const partCatalog: Record<PartKind, PartDefinition> = rawCatalog;
export const partKinds = Object.keys(partCatalog) as PartKind[];
/** The kind whose drawing a part uses: its own, unless the catalogue says it borrows one. */
export const lookOf = (kind: PartKind): PartKind => partCatalog[kind]?.look ?? kind;
export const partValues = (part: { kind: PartKind; values?: number[] }): number[] =>
  part.values ?? partCatalog[part.kind].defaultValues ?? [];
export const partContext = (part: {
  kind: PartKind;
  value: number;
  values?: number[];
}): PartContext => ({ value: part.value, values: partValues(part) });
export function controlError(control: PartControl, value: number): string | null {
  const fail = control.error ?? `${control.label}: недопустимое значение.`;
  if (!Number.isFinite(value)) return fail;
  if (control.kind === 'momentary' || control.kind === 'toggle')
    return value === 0 || value === 1 ? null : fail;
  if (control.kind === 'range')
    return value >= control.min! && value <= control.max!
      ? null
      : (control.error ?? `${control.label}: ${control.min}…${control.max}${control.unit ?? ''}.`);
  if (control.kind === 'select')
    return control.options!.some((option) => option.value === value)
      ? null
      : (control.error ??
          `${control.label}: ${control.options!.map((option) => option.label).join(', ')}.`);
  if (control.kind === 'bits')
    return Number.isInteger(value) && value >= 0 && value < 2 ** control.bits! ? null : fail;
  return null;
}
export interface InputControl {
  index: number;
  control: PartControl;
}
export function inputControls(kind: PartKind): InputControl[] {
  const definition = partCatalog[kind];
  return [
    ...(definition.control.scenario ? [{ index: -1, control: definition.control }] : []),
    ...(definition.extras ?? []).flatMap((control, index) =>
      control.scenario ? [{ index, control }] : [],
    ),
  ];
}
export const canvasSliders = (kind: PartKind): InputControl[] => {
  const definition = partCatalog[kind];
  return [
    ...(definition.control.kind === 'range' && definition.control.canvas
      ? [{ index: -1, control: definition.control }]
      : []),
    ...(definition.extras ?? []).flatMap((control, index) =>
      control.kind === 'range' && control.canvas ? [{ index, control }] : [],
    ),
  ];
};
/** Pin names of this particular part (breadboards grow with their size). */
export function partPinNames(part: { kind: PartKind; value: number; values?: number[] }) {
  const definition = partCatalog[part.kind];
  return definition.pinsFor ? definition.pinsFor(partContext(part)) : definition.pins;
}
export function partSize(kind: PartKind) {
  const definition = partCatalog[kind],
    sliders = canvasSliders(kind).length;
  const width = definition.width ?? 150,
    height = definition.height ?? 94;
  return { width, height, outline: height + 48 + (sliders ? 52 + (sliders - 1) * 28 : 0) };
}
