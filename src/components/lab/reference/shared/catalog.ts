export type IconKey = (typeof iconKeys)[number];
export type ControlKind = 'none' | 'momentary' | 'toggle' | 'range' | 'select' | 'bits';
export interface PartControl {
  kind: ControlKind;
  label: string;
  min?: number;
  max?: number;
  step?: number;
  unit?: string;
  options?: { value: number; label: string }[];
  bits?: number;
  captions?: [string, string];
  presets?: number[];
  error?: string;
  scenario?: boolean;
  canvas?: boolean;
  pad?: boolean;
}
export interface PartContext {
  value: number;
  values: number[];
}
export type DriveFn = (part: PartContext, high: number, low: number) => number;
export type PartKind = keyof typeof rawCatalog;
export interface PartDefinition {
  name: string;
  category: PartCategory;
  icon: IconKey;
  pins: string[];
  defaultValue: number;
  color: string;
  control: PartControl;
  extras?: PartControl[];
  defaultValues?: number[];
  width?: number;
  height?: number;
  layout?: 'bottom' | 'ends';
  supply?: { vcc?: string; gnd?: string; min: number };
  help?: string;
  family?: string;
  /** The kind whose model draws this part (kinds the laboratory adds borrow a model). */
  look?: PartKind;
  emit?: { anodes: string[]; cathode: string; resistor: boolean; swappable?: boolean };
  drive?: Record<string, DriveFn>;
  joins?: (part: PartContext) => [string, string][];
  /** Pins that depend on the part's value, e.g. breadboard size; `pins` lists the superset. */
  pinsFor?: (part: PartContext) => string[];
  load?: { pin: string; invertible?: boolean };
  outputs?: { pins: string[]; weakHigh: boolean };
  i2c?: boolean | number;
  spi?: { mosi: string; sck: string; miso?: string; cs?: string };
}
const none: PartControl = { kind: 'none', label: '' };
const hex = (n: number) => '0x' + n.toString(16).toUpperCase().padStart(2, '0');
const addresses = (list: number[]): PartControl => ({
  kind: 'select',
  label: 'I²C адрес',
  options: list.map((value) => ({ value, label: hex(value) })),
});
const range = (
  label: string,
  min: number,
  max: number,
  unit = '',
  step = 1,
  extra: Partial<PartControl> = {},
): PartControl => ({ kind: 'range', label, min, max, unit, step, scenario: true, ...extra });
const toggle = (label: string, off: string, on: string): PartControl => ({
  kind: 'toggle',
  label,
  captions: [off, on],
  scenario: true,
});
const triggerLevel: PartControl = {
  kind: 'select',
  label: 'Активный уровень',
  options: [
    { value: 0, label: 'HIGH включает' },
    { value: 1, label: 'LOW включает' },
  ],
};
const lcdAddresses = addresses([0x27, 0x3f, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x38]);
const expanderAddresses = addresses([
  0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x38, 0x39, 0x3a, 0x3b, 0x3c, 0x3d, 0x3e, 0x3f,
]);
const wide = (pins: number) => Math.max(150, 30 * (pins + 1));
const seg = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'DP'];
const bar = Array.from({ length: 10 }, (_, i) => 'L' + (i + 1));
const lerp = (part: PartContext, high: number, low: number, fraction: number) =>
  low + (high - low) * Math.max(0, Math.min(1, fraction));
const analog = (fraction: (v: number) => number): Record<string, DriveFn> => ({
  AO: (p, h, l) => lerp(p, h, l, fraction(p.value)),
});
const digital = (pin: string, activeLow: boolean): Record<string, DriveFn> => ({
  [pin]: (p, h, l) => ((p.value === 1) !== activeLow ? h : l),
});
const ntcResistance = (celsius: number) =>
  10000 * Math.exp(3950 * (1 / (celsius + 273.15) - 1 / 298.15));
const digitalSensor = (
  name: string,
  icon: IconKey,
  color: string,
  captions: [string, string],
  activeLow: boolean,
  help: string,
  pins = ['VCC', 'GND', 'OUT'],
) => ({
  name,
  category: 'sensors' as PartCategory,
  icon,
  pins,
  defaultValue: 0,
  color,
  control: toggle('Состояние', ...captions),
  supply: { vcc: 'VCC', gnd: 'GND', min: 2.7 },
  drive: digital('OUT', activeLow),
  help,
});
const analogSensor = (
  name: string,
  icon: IconKey,
  color: string,
  label: string,
  min: number,
  max: number,
  unit: string,
  defaultValue: number,
  fraction: (v: number) => number,
  help: string,
) => ({
  name,
  category: 'sensors' as PartCategory,
  icon,
  pins: ['VCC', 'GND', 'AO'],
  defaultValue,
  color,
  control: range(label, min, max, unit, 1, { canvas: true }),
  supply: { vcc: 'VCC', gnd: 'GND', min: 2.7 },
  drive: analog(fraction),
  help,
});
const busSensorPins = ['VCC', 'GND', 'SDA', 'SCL'];
/** Comparator module (LM393) with analog AO and a threshold output DO that goes LOW above 50 %. */
const comboSensor = (
  name: string,
  icon: IconKey,
  color: string,
  label: string,
  min: number,
  max: number,
  unit: string,
  defaultValue: number,
  fraction: (v: number) => number,
  help: string,
) => ({
  ...analogSensor(name, icon, color, label, min, max, unit, defaultValue, fraction, help),
  pins: ['VCC', 'GND', 'DO', 'AO'],
  drive: {
    ...analog(fraction),
    DO: ((p, h, l) => (fraction(p.value) > 0.5 ? l : h)) as DriveFn,
  },
});
