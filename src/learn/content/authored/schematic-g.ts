/** Одна проверка: выход читается в конце такта `cycle`, после его фронта. */
const at = (
  cycle: number,
  inputs: Record<string, string>,
  expected: string,
  title: string,
): LessonCase => ({ title, cycle, inputs, expected });

/** Входы по тактам: ряд `rows` начинается с такта `from`. */
const seqOf = (from: number, rows: Record<string, string>[]) =>
  rows.map((inputs, at) => ({ cycle: from + at, inputs }));

