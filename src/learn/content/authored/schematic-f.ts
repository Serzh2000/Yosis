/*
 * Счётчики и делители. Выход читается в конце такта `cycle`, то есть после его положительного
 * фронта. Сброс `reset` здесь обычный вход схемы: его держат в 1 первые два такта (чтобы счётчик
 * получил известное значение), а потом при необходимости ещё раз посреди счёта. Симулятор не даёт
 * менять сброс, который он сам создаёт (`config.reset`), поэтому сброс задан через `stimuli`.
 * Ожидаемые значения считает небольшая модель ниже: она повторяет правила блока такт за тактом, а
 * настоящая проверка сверяет её с симулятором.
 */

interface Stimulus {
  cycle: number;
  inputs: Record<string, string>;
}
interface Plan {
  cycles: number;
  /** Сброс reset держится первые два такта: так счётчик получает известное значение. */
  reset?: boolean;
  inputs: Record<string, string>;
  stimuli: Stimulus[];
}

/** Расписание входов: сброс в начале, если он нужен, и изменения из плана. */
const schedule = (plan: Plan): Stimulus[] =>
  [
    ...(plan.reset
      ? [
          { cycle: 0, inputs: { reset: '1' } },
          { cycle: 2, inputs: { reset: '0' } },
        ]
      : []),
    ...plan.stimuli,
  ].sort((a, b) => a.cycle - b.cycle);

const settings = (plan: Plan): Partial<SimulationConfig> => ({
  clock: 'clk',
  reset: null,
  periodNs: 10,
  cycles: plan.cycles,
  inputs: plan.inputs,
  stimuli: schedule(plan),
});

/** Прогоняет модель такт за тактом и выдаёт проверки для выбранных тактов. */
function trace(
  plan: Plan,
  width: number,
  step: (q: number, v: Record<string, number>) => number,
  picks: [cycle: number, title: string][],
  view: (q: number) => number = (q) => q,
): LessonCase[] {
  const last = Math.max(...picks.map(([cycle]) => cycle));
  const wanted = new Map(picks);
  const current: Record<string, string> = { ...plan.inputs };
  const events = schedule(plan);
  let q = 0;
  const cases: LessonCase[] = [];
  for (let cycle = 0; cycle <= last; cycle++) {
    for (const event of events.filter((item) => item.cycle === cycle))
      for (const [name, value] of Object.entries(event.inputs)) {
        current[name] = value;
      }
    const values: Record<string, number> = Object.fromEntries(
      Object.entries(current).map(([name, value]) => [name, Number(value)]),
    );
    values.reset = Number(current.reset ?? 0);
    q = step(q, values);
    const title = wanted.get(cycle);
    if (title)
      cases.push({
        title,
        cycle,
        inputs: { ...current },
        expected: view(q).toString(2).padStart(width, '0'),
      });
  }
  return cases;
}

