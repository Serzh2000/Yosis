const bin = (n: number, w: number) =>
  (((n % 2 ** w) + 2 ** w) % 2 ** w).toString(2).padStart(w, '0');

/** Cases for a circuit of two 4-bit numbers: one case per pair, the title shows the numbers. */
function pairs(
  list: [number, number][],
  f: (a: number, b: number) => number,
  outWidth: number,
  sign: string,
): LessonCase[] {
  return list.map(([a, b], cycle) => ({
    title: `${a} ${sign} ${b}`,
    cycle,
    inputs: { a: '0b' + bin(a, 4), b: '0b' + bin(b, 4) },
    expected: bin(f(a, b), outWidth),
  }));
}

/** Cases for a circuit of one 4-bit number. */
function singles(list: number[], f: (a: number) => number, outWidth: number): LessonCase[] {
  return list.map((a, cycle) => ({
    title: `a = ${a}`,
    cycle,
    inputs: { a: '0b' + bin(a, 4) },
    expected: bin(f(a), outWidth),
  }));
}

