const bin = (n: number, width: number) => n.toString(2).padStart(width, '0');

/** Cases from pairs of (inputs, expected), the cycle counting from 0. */
const listed = (rows: [Record<string, string>, string][]): LessonCase[] =>
  rows.map(([inputs, expected], index) => ({
    title: t('Случай {n}', { n: index + 1 }),
    cycle: index,
    inputs,
    expected,
  }));

/** The truth table of 1-bit inputs given by a function of the bits (first name is the top bit). */
const byRule = (names: string[], rule: (bits: number[]) => string) =>
  table(
    names,
    Array.from({ length: 2 ** names.length }, (_, row) =>
      rule(names.map((_, at) => (row >> (names.length - 1 - at)) & 1)),
    ),
  );

const mux2Rule = ([d0, d1, s]: number[]) => String(s ? d1 : d0);

