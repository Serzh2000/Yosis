/** Cases for buses: each row gives the binary input strings (turned into decimal for the simulator) and the expected output string. */
function rows(items: [Record<string, string>, string][]) {
  return items.map(([inputs, expected], i) => ({
    title: t('Случай {n}', { n: i + 1 }),
    cycle: i,
    inputs: Object.fromEntries(
      Object.entries(inputs).map(([name, bits]) => [name, String(parseInt(bits, 2))]),
    ),
    expected,
  }));
}
const bin = (n: number, w: number) => n.toString(2).padStart(w, '0');

