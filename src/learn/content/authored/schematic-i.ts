const raw = (value: number, width: number) => value.toString(2).padStart(width, '0');
const bin = (value: number, width: number) => '0b' + raw(value, width);

/** Сегменты a…g: бит 0 — сегмент a, бит 6 — сегмент g (как в блоке «BCD → 7 сегментов»). */
const SEGMENTS = [
  0x3f, 0x06, 0x5b, 0x4f, 0x66, 0x6d, 0x7d, 0x07, 0x7f, 0x6f, 0x77, 0x7c, 0x39, 0x5e, 0x79, 0x71,
];

/** Один случай на каждое значение числа n шириной `width`. */
const numberCases = (
  values: number[],
  width: number,
  title: (n: number) => string,
  expected: (n: number) => string,
): LessonCase[] =>
  values.map((n, cycle) => ({
    title: title(n),
    cycle,
    inputs: { n: bin(n, width) },
    expected: expected(n),
  }));

const range = (count: number) => Array.from({ length: count }, (_, i) => i);

