const bin = (n: number, w: number) =>
  (((n % 2 ** w) + 2 ** w) % 2 ** w).toString(2).padStart(w, '0');
const signed = (n: number, w: number) => (n >= 2 ** (w - 1) ? n - 2 ** w : n);

/** Cases for a list of input tuples: `names` with widths, `f` gives the expected number. */
function cases(
  names: [string, number][],
  rows: number[][],
  out: number,
  f: (...v: number[]) => number,
): LessonCase[] {
  return rows.map((row, at) => ({
    title: `${names.map(([n], i) => `${n}=${row[i]}`).join(', ')}`,
    cycle: at,
    inputs: Object.fromEntries(names.map(([n], i) => [n, String(row[i])])),
    expected: bin(f(...row), out),
  }));
}
const all = (...sizes: number[]): number[][] =>
  sizes.reduce<number[][]>(
    (acc, s) => acc.flatMap((r) => Array.from({ length: s }, (_, v) => [...r, v])),
    [[]],
  );

