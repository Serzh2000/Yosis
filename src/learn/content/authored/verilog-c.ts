const bin = (n: number, width: number) => n.toString(2).padStart(width, '0');

/** One case per 4-bit value of the input; `f` gives the expected output as a number. */
function all16(f: (a: number) => number, outWidth: number, name = 'a'): LessonCase[] {
  return Array.from({ length: 16 }, (_, a) => ({
    title: `${name} = ${bin(a, 4)}`,
    cycle: a,
    inputs: { [name]: String(a) },
    expected: bin(f(a), outWidth),
  }));
}

const rev4 = (a: number) => parseInt(bin(a, 4).split('').reverse().join(''), 2);
const rol4 = (a: number) => ((a << 1) | (a >> 3)) & 15;
const gray = (a: number) => a ^ (a >> 1);
const ungray = (g: number) => g ^ (g >> 1) ^ (g >> 2) ^ (g >> 3);
const ones = (a: number) => bin(a, 4).split('1').length - 1;
const SEG = [
  0x3f, 0x06, 0x5b, 0x4f, 0x66, 0x6d, 0x7d, 0x07, 0x7f, 0x6f, 0x77, 0x7c, 0x39, 0x5e, 0x79, 0x71,
];

const shiftCases: LessonCase[] = [];
for (let dir = 0; dir < 2; dir++)
  for (let a = 0; a < 16; a++)
    shiftCases.push({
      title: `a = ${bin(a, 4)}, dir = ${dir}`,
      cycle: shiftCases.length,
      inputs: { a: String(a), dir: String(dir) },
      expected: bin(dir ? a >> 1 : (a << 1) & 15, 4),
    });

const barrelCases: LessonCase[] = [];
for (const a of [0b00000001, 0b10110101, 0b11111111, 0b01100110, 0b10000001, 0b00010010])
  for (let s = 0; s < 4; s++)
    barrelCases.push({
      title: `a = ${bin(a, 8)}, s = ${bin(s, 2)}`,
      cycle: barrelCases.length,
      inputs: { a: String(a), s: String(s) },
      expected: bin((a << s) & 255, 8),
    });

