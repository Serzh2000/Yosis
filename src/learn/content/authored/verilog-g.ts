/** Input values are decimal in the simulator; the lessons write them in binary. */
function dec(inputs: Record<string, string>): Record<string, string> {
  return Object.fromEntries(
    Object.entries(inputs).map(([name, value]) => [name, String(parseInt(value, 2))]),
  );
}

/** Cases of a circuit without a clock: each row is the inputs of one period and the expected output. */
function comb(rows: [Record<string, string>, string][]): LessonCase[] {
  return rows.map(([inputs, expected], at) => ({
    title: Object.entries(inputs)
      .map(([name, value]) => `${name} = ${value}`)
      .join(', '),
    cycle: at,
    inputs: dec(inputs),
    expected,
  }));
}

