/** Случаи по тактам: одна строка на такт, значения входов и ожидаемый выход. */
const run = (
  rows: { inputs: Record<string, string>; expected: string; title?: string }[],
): LessonCase[] =>
  rows.map((row, cycle) => ({
    title: row.title ?? t('Такт {n}', { n: cycle }),
    cycle,
    inputs: row.inputs,
    expected: row.expected,
  }));

/**
 * Входы меняются уже ПОСЛЕ фронта такта (на 1 нс позже), как у настоящей кнопки: схема ещё
 * «помнит» старое значение, а провод уже показывает новое.
 */
const late = (rows: Record<string, string>[]) =>
  rows.flatMap((inputs, cycle) =>
    Object.keys(inputs).length ? [{ timeNs: cycle * 10 + 6, inputs }] : [],
  );

