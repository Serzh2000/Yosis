const rows = (count: number, value: (row: number) => number, width = 1) =>
  Array.from({ length: count }, (_, row) => value(row).toString(2).padStart(width, '0'));

const aluRow = (row: number) => {
  const a = (row >> 4) & 3,
    b = (row >> 2) & 3,
    op = row & 3;
  return [(a + b) & 7, (a - b) & 7, a & b, a | b][op]!;
};
const ones = (value: number) => value.toString(2).split('1').length - 1;

