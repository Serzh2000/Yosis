/** Число v в двоичной строке ширины w. */
const bin = (v: number, w: number) => v.toString(2).padStart(w, '0');

/** Случаи для схемы без такта: по одному на набор входов, такт — номер случая. */
const cases = (
  rows: { title: string; inputs: Record<string, string>; expected: string }[],
): LessonCase[] => rows.map((row, cycle) => ({ ...row, cycle }));

/** Пары (a, b) шириной 4 бита; expected считает функция f. */
const pairCases = (pairs: [number, number][], f: (a: number, b: number) => string) =>
  cases(
    pairs.map(([a, b]) => ({
      title: `a = ${a}, b = ${b}`,
      inputs: { a: '0b' + bin(a, 4), b: '0b' + bin(b, 4) },
      expected: f(a, b),
    })),
  );

const pairs: [number, number][] = [
  [0, 0],
  [5, 5],
  [15, 15],
  [3, 5],
  [5, 3],
  [8, 0],
  [0, 8],
  [7, 8],
  [8, 7],
  [15, 0],
  [0, 15],
  [12, 13],
  [13, 12],
];

const ones = (v: number) => v.toString(2).split('1').length - 1;

