function explain(
  id: string,
  title: string,
  text: string,
  code?: string,
  workspace?: CourseStep['workspace'],
): CourseStep {
  return { id, title, kind: 'explain', text, code, workspace };
}
function quiz(
  id: string,
  title: string,
  question: string,
  options: Array<[string, string]>,
  correct = 0,
): CourseStep {
  return {
    id,
    title,
    kind: 'quiz',
    text: 'Выбери ответ. Если ошибёшься, разберём именно твой вариант, и можно попробовать снова.',
    quiz: {
      question,
      correctOptionId: String(correct),
      options: options.map(([label, feedback], index) => ({ id: String(index), label, feedback })),
    },
  };
}
function practice(text: string): CourseStep {
  return { id: 'practice', title: 'Попробуй сам', kind: 'practice', text, workspace: 'code' };
}

const baseConfig: SimulationConfig = {
  clock: null,
  reset: null,
  resetActiveLow: false,
  resetCycles: 0,
  cycles: 10,
  periodNs: 10,
  inputs: {},
};
function combinational(inputs: Record<string, string>[], expected: string[]): LessonCase[] {
  return inputs.map((values, cycle) => ({
    title: `Проверка ${cycle + 1}`,
    cycle,
    inputs: values,
    expected: expected[cycle],
  }));
}
function combinationalConfig(cases: LessonCase[]): SimulationConfig {
  return {
    ...baseConfig,
    cycles: cases.length + 1,
    inputs: cases[0].inputs,
    stimuli: cases.slice(1).map((item) => ({ cycle: item.cycle, inputs: item.inputs })),
  };
}
function project(name: string, content: string): Project {
  const notes = '// Учебная лаборатория: входы и такты для проверки подаёт симулятор.\n';
  return {
    name,
    top: 'top',
    board: 'tangnano20k',
    files: [{ name: 'top.v', content: notes + content }],
  };
}
const binary = (value: number, width: number) => value.toString(2).padStart(width, '0');

type ExerciseSpec = Pick<
  Lesson,
  'id' | 'title' | 'description' | 'concept' | 'objective' | 'hint' | 'output' | 'cases'
> & { source: string; config?: SimulationConfig };
function exercise(number: number, spec: ExerciseSpec): Lesson {
  return {
    id: spec.id,
    number: String(number).padStart(2, '0'),
    title: spec.title,
    description: spec.description,
    concept: spec.concept,
    minutes: 4,
    level: beginnerLevels[1].title,
    question: spec.objective,
    choices: ['Выполнить задание'],
    answer: 0,
    explanation: 'Проверка запускает настоящий симулятор и сравнивает выходы с ожидаемыми.',
    objective: spec.objective,
    hint: spec.hint,
    output: spec.output,
    cases: spec.cases,
    config: spec.config ?? combinationalConfig(spec.cases),
    project: project(`learn-${spec.id}`, spec.source),
  };
}

