export interface ExampleLesson {
  level: CurriculumLevel;
  topic: CurriculumTopic;
  /** Authored learning order; unrelated to line count or FPGA resource count. */
  order: number;
  objective: string;
  prerequisites: string[];
  observe: string;
  experiment: string;
}

function lesson(
  level: CurriculumLevel,
  topic: CurriculumTopic,
  objective: string,
  prerequisites: string[],
  observe: string,
  experiment: string,
): Omit<ExampleLesson, 'order'> {
  return { level, topic, objective, prerequisites, observe, experiment };
}

