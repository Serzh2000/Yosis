export type CurriculumExampleId = keyof typeof lessons;
export const exampleCurriculum = Object.fromEntries(
  Object.entries(lessons).map(([id, entry], order) => [id, { ...entry, order }]),
) as Record<CurriculumExampleId, ExampleLesson>;

export function getExampleLesson(id: string): ExampleLesson | undefined {
  return Object.hasOwn(exampleCurriculum, id)
    ? exampleCurriculum[id as CurriculumExampleId]
    : undefined;
}

export function compareCurriculumExamples(a: { id: string }, b: { id: string }): number {
  const first = getExampleLesson(a.id),
    second = getExampleLesson(b.id);
  return (
    (first?.level ?? 5) - (second?.level ?? 5) ||
    (first?.order ?? Number.MAX_SAFE_INTEGER) - (second?.order ?? Number.MAX_SAFE_INTEGER) ||
    a.id.localeCompare(b.id)
  );
}
