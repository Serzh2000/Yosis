"""Add truthful Gowin Programmer metadata; configuration bytes are unchanged.

This is a local diagnostic adapter, not the server's programming transport.
Apicula's reader checks each frame CRC before any output is written.
"""
from hashlib import sha256
from pathlib import Path
from apycula.bslib import read_bitstream

root = Path(__file__).resolve().parent
source = root / "design.fs"
_, header, footer, slots = read_bitstream(source)
assert not slots
device = next(row for row in header if row[0] == 0x06)
assert int.from_bytes(device[-4:], "big") == 0x0000081B
code = next(row for row in footer if row[0] == 0x0A)
usercode = int.from_bytes(code[-4:], "big")
body = source.read_bytes()
assert not body.startswith(b"//"), "Expected the original Apicula artifact"
comments = f"""//Generated by Apicula 0.32 through Yosis; metadata adapter for Gowin Programmer.
//File Title: Bitstream file
//Device: GW2AR-18
//Device Version: C
//Part Number: GW2AR-LV18QN88C8/I7
//Device-package: GW2AR-18C-QFN88
//BackgroundProgramming: OFF
//CheckSum: 0x{usercode:04X}
//UserCode: 0x{usercode:08X}
//LoadingRate: 2.500MHz
//CRCCheck: ON
//Compress: OFF
//Encryption: OFF
//SecurityBit: ON
//SecureMode: OFF
//JTAGAsRegularIO: OFF
//MultiBootSPIAddr: 0x00000000
""".encode("ascii")
output = root / "design-programmer.fs"
output.write_bytes(comments + body)
assert output.read_bytes()[len(comments):] == body
read_bitstream(output)
print(f"CRC valid; original binary rows unchanged; UserCode=0x{usercode:08X}")
print(f"{output.name}: SHA256 {sha256(output.read_bytes()).hexdigest()}")
