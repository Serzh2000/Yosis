async function complete<T extends { id: string; status: string; stage: string; error?: string; logs: string }>(job: T, get: (id: string) => Promise<T>) {
    const deadline = Date.now() + 300000;
    let stage = '';
    while (['queued', 'running'].includes(job.status)) {
        assert.ok(Date.now() < deadline, 'Build deadline exceeded');
        if (job.stage !== stage) { stage = job.stage; console.log(stage); }
        await new Promise(resolve => setTimeout(resolve, 500));
        job = await get(job.id);
    }
    assert.equal(job.status, 'success', `${job.error}\n${job.logs.slice(-6000)}`);
    return job;
}

// Python is used only for Apicula's independent frame-CRC reader and file adapter.
// It never loads a USB DLL or invokes a programmer.
const addProgrammerMetadata = String.raw`
from pathlib import Path
from hashlib import sha256
import sys
from apycula.bslib import read_bitstream
source, output = (Path(value) for value in sys.argv[1:])
_, header, footer, slots = read_bitstream(str(source))
assert not slots
device = next(row for row in header if row[0] == 0x06)
assert int.from_bytes(device[-4:], 'big') == 0x0000081B
code = next(row for row in footer if row[0] == 0x0A)
usercode = int.from_bytes(code[-4:], 'big')
settings = int.from_bytes(next(row for row in header if row[0] == 0x10), 'big')
assert not settings & (1 << 13), 'Unexpected compressed bitstream'
rate_code = (settings >> 16) & 0xff
rate = 2500000 if not rate_code else 125000000 / ((((rate_code & 0x7f) ^ 0x44) >> 2) + 1)
security = 'ON' if any(row[0] == 0x0B for row in header) else 'OFF'
body = source.read_bytes()
assert not body.startswith(b'//'), 'Expected original Apicula artifact'
comments = f'''//Generated by Apicula through Yosis; metadata adapter for Gowin Programmer.
//File Title: Bitstream file
//Device: GW2AR-18
//Device Version: C
//Part Number: GW2AR-LV18QN88C8/I7
//Device-package: GW2AR-18C-QFN88
//BackgroundProgramming: OFF
//CheckSum: 0x{usercode:04X}
//UserCode: 0x{usercode:08X}
//LoadingRate: {rate / 1000000:.6f}MHz
//CRCCheck: ON
//Compress: OFF
//Encryption: OFF
//SecurityBit: {security}
//SecureMode: OFF
//JTAGAsRegularIO: OFF
//MultiBootSPIAddr: 0x00000000
'''.encode('ascii')
output.write_bytes(comments + body)
assert output.read_bytes()[len(comments):] == body
read_bitstream(str(output))
print(f'CRC valid; original binary rows unchanged; UserCode=0x{usercode:08X}')
print(f'{output.name}: SHA256 {sha256(output.read_bytes()).hexdigest()}')
`;

