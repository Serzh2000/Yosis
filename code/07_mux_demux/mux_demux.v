// Пример 7. Дешифратор, мультиплексор и демультиплексор на плате.
// Кнопки S1, S2 задают двухбитный адрес s.
//   led[4]   -- выход мультиплексора 4:1: мигает с частотой, выбранной адресом;
//   led[3:0] -- выходы демультиплексора 1:4: мигающий сигнал попадает
//               только на светодиод с номером s.
module mux_demux (
    input  wire       clk,       // 27 МГц
    input  wire [1:0] btn,       // адрес s = {S2, S1}
    output wire [5:0] led
);
    // Счётчик-делитель: его старшие разряды -- четыре сигнала разной частоты
    reg [24:0] cnt = 0;
    always @(posedge clk) cnt <= cnt + 1'b1;

    wire [3:0] x = cnt[24:21];   // ~0,8 Гц, ~1,6 Гц, ~3,2 Гц, ~6,4 Гц
    wire [1:0] s = btn;

    // Мультиплексор 4:1 -- два уровня мультиплексоров 2:1 (дерево)
    wire m0 = s[0] ? x[1] : x[0];
    wire m1 = s[0] ? x[3] : x[2];
    wire y  = s[1] ? m1   : m0;

    // Дешифратор 2 -> 4: единица на выходе с номером s
    reg [3:0] dc;
    always @(*) begin
        case (s)
            2'd0:    dc = 4'b0001;
            2'd1:    dc = 4'b0010;
            2'd2:    dc = 4'b0100;
            default: dc = 4'b1000;
        endcase
    end

    // Демультиплексор 1:4 = дешифратор, у которого вход разрешения --
    // информационный сигнал (здесь -- мигание ~1,6 Гц)
    wire       data  = cnt[23];
    wire [3:0] demux = dc & {4{data}};

    // led[5] не используется; инверсия -- светодиоды горят от нуля
    assign led = ~{1'b0, y, demux};
endmodule
